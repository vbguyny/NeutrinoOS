#!/usr/bin/env python3
# Generate C# HPACK tables (RFC 7541: static table + Huffman code table)
# from the reference `hpack` Python library, written directly into the
# NeutrinoOS source tree.
import sys

try:
    import hpack
except ImportError:
    print('hpack not installed', file=sys.stderr)
    sys.exit(1)

from hpack.huffman_constants import REQUEST_CODES, REQUEST_CODES_LENGTH
from hpack.table import HeaderTable
STATIC_TABLE = HeaderTable.STATIC_TABLE

out = []
out.append('// ProtonOS DDK - HPACK tables (RFC 7541), GENERATED by')
out.append('// build/gen-hpack-tables.py from the reference `hpack` library.')
out.append('// Do not edit by hand; re-run the generator to refresh.')
out.append('')
out.append('namespace ProtonOS.DDK.Services;')
out.append('')
out.append('/// <summary>Static HPACK tables (RFC 7541).</summary>')
out.append('public static class HpackTables')
out.append('{')
out.append('    /// <summary>Number of generated Huffman codes (0..255 + EOS).</summary>')
out.append('    public const int HuffmanSymbols = 257;')
out.append('')
out.append('    /// <summary>Huffman code values, one per byte value; index 256 = EOS.</summary>')
out.append('    public static readonly uint[] HuffmanCodes = new uint[]')
out.append('    {')
codes = list(REQUEST_CODES) + [0x3FFFFFFF]  # EOS 30 bits
lens = list(REQUEST_CODES_LENGTH) + [30]
for i in range(0, len(codes), 8):
    row = ', '.join('0x%08X' % c for c in codes[i:i+8])
    out.append('        ' + row + ',')
out.append('    };')
out.append('')
out.append('    /// <summary>Huffman code bit lengths; index 256 = EOS (30 bits).</summary>')
out.append('    public static readonly byte[] HuffmanLengths = new byte[]')
out.append('    {')
for i in range(0, len(lens), 16):
    row = ', '.join('%d' % l for l in lens[i:i+16])
    out.append('        ' + row + ',')
out.append('    };')
out.append('')

# Static table: name + value pairs (61 entries; hpack exposes header tuples)
out.append('    /// <summary>HPACK static table (RFC 7541 appendix A), name/value pairs.</summary>')
out.append('    public static readonly string[] StaticNames = new string[]')
out.append('    {')
for name, value in STATIC_TABLE:
    n = name.decode() if isinstance(name, bytes) else name
    out.append('        "%s",' % n)
out.append('    };')
out.append('')
out.append('    public static readonly string[] StaticValues = new string[]')
out.append('    {')
for name, value in STATIC_TABLE:
    v = value.decode() if isinstance(value, bytes) else value
    v = v.replace('\\', '\\\\').replace('"', '\\"')
    out.append('        "%s",' % v)
out.append('    };')
out.append('}')

target = '/mnt/d/Projects/Code/NeutrinoOS/src/ddk/Services/HpackTables.cs'
with open(target, 'w', newline='\n') as f:
    f.write('\n'.join(out) + '\n')
print('wrote', target, len(STATIC_TABLE), 'static entries')
